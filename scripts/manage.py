def demo_user():
    from veritagnosis import db
    from veritagnosis import security as auth
    # token_urlsafe draws from letters, digits, - and _, so a given one may
    # happen to miss a class the policy requires. Draw until one passes rather
    # than hand-building a password that is weaker than the rule it satisfies.
    from veritagnosis import crypto as passwords
    pw = ""
    while not pw or passwords.problems(pw):
        pw = secrets.token_urlsafe(12) + secrets.choice("!?@#$%&*")
    with db.get_session() as s:
        try:
            user = auth.register(s, "demo", pw, email="demo@example.com",
                                 age="17", gender="unspecified")
            # Read inside the session: once it closes the row is detached and
            # touching user.id raised DetachedInstanceError, which hid the
            # one-time password the account had just been created with.
            uid = user.id
        except auth.RegistrationError as e:
            print(f"Could not create demo user: {e}")
            return 1
    print(f"username: demo\npassword: {pw}\nuser id:  {uid}")
    print("Shown once. It is hashed with Argon2id and cannot be recovered.")
    return 0


def email_setup():
    """Walk through connecting the one Gmail account the app sends FROM.

    Worth being clear about, because it is the most misunderstood part: the app
    does NOT log into each user's Gmail. Google does not allow that, and no app
    works that way. There is ONE sending account - yours - and it emails codes
    TO whatever address each person typed at signup. Your users configure
    nothing; they just receive an email.
    """
    print(__doc__ and "")
    print("Connecting Gmail so codes can be emailed")
    print("=" * 46)
    print()
    print("The app sends from ONE account (yours) to every user's address.")
    print("Your users never set anything up - they just get an email.")
    print()
    print("1. Go to  https://myaccount.google.com/security")
    print("2. Turn on 2-Step Verification (Google requires it for step 3)")
    print("3. Go to  https://myaccount.google.com/apppasswords")
    print("4. Create one named 'Veritagnosis' and copy the 16 characters")
    print()
    addr = input("Your Gmail address: ").strip()
    pw = input("The 16-character app password: ").replace(" ", "").strip()
    if not addr or not pw:
        print("\nNothing entered - leaving .env unchanged.")
        return 1
    if not ENV.exists():
        print("\nNo .env yet. Run:  python scripts/manage.py init-keys")
        return 1

    lines, seen = [], set()
    for line in ENV.read_text(encoding="utf-8").splitlines():
        key = line.split("=")[0].strip()
        if key == "VG_SMTP_USER":
            lines.append(f"VG_SMTP_USER={addr}"); seen.add(key)
        elif key == "VG_SMTP_PASSWORD":
            lines.append(f"VG_SMTP_PASSWORD={pw}"); seen.add(key)
        else:
            lines.append(line)
    if "VG_SMTP_USER" not in seen:
        lines += [f"VG_SMTP_USER={addr}", f"VG_SMTP_PASSWORD={pw}"]
    ENV.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"\nSaved to {ENV}")
    print("Now check it works:  python scripts/manage.py email-test")
    return 0


def email_test():
    """Send a real code to yourself, so you know it works before a user hits it."""
    from veritagnosis import config, mailer
    if not mailer.is_configured():
        print("Email is not set up yet. Run:  python scripts/manage.py email-setup")
        return 1
    to = input(f"Send a test code to [{config.smtp_user()}]: ").strip() or config.smtp_user()
    try:
        sent = mailer.send_verification_code(to, "123456")
    except mailer.MailError as e:
        print(f"\nFAILED: {e}")
        return 1
    print(f"\nSent to {to}. Check the inbox (and spam, the first time)."
          if sent else "\nNot sent - email is not configured.")
    return 0


def check():
    """Report on configuration. Fails loudly rather than reassuring you."""
    import os
    ok = True

    def line(good, msg):
        nonlocal ok
        ok = ok and good
        print(f"  [{'OK ' if good else 'FAIL'}] {msg}")

    print("Security configuration:")
    line(ENV.exists(), ".env exists")

    gitignore = (BASE / ".gitignore")
    ignored = gitignore.exists() and ".env" in gitignore.read_text(encoding="utf-8")
    line(ignored, ".env is listed in .gitignore")

    try:
        from veritagnosis import config
        config.field_key(); config.index_key()
        line(True, "encryption keys load and pass length checks")
    except Exception as e:
        line(False, f"encryption keys: {e}")

    try:
        import argon2  # noqa: F401
        line(True, "argon2-cffi installed (Argon2id password hashing)")
    except ImportError:
        line(False, "argon2-cffi missing — passwords cannot be hashed")

    enc = os.environ.get("VG_ENCRYPT_DB") == "1"
    if enc:
        try:
            import sqlcipher3  # noqa: F401
            line(True, "whole-file encryption on, sqlcipher3 available")
        except ImportError:
            line(False, "VG_ENCRYPT_DB=1 but sqlcipher3-binary is not installed")
    else:
        print("  [ -- ] whole-file encryption off (field encryption still active)")

    try:
        from veritagnosis import mailer
        if mailer.is_configured():
            line(True, "Gmail is connected - codes will be emailed to users")
        else:
            print("  [ -- ] Gmail not connected - codes print in the terminal")
            print("         set it up with: python scripts/manage.py email-setup")
    except Exception as e:  # noqa: BLE001
        line(False, f"email check failed: {e}")

    db_file = BASE / "data" / "veritagnosis.db"
    if db_file.exists():
        raw = db_file.read_bytes()
        # Cheap canary: the demo values should never appear in the clear.
        leaked = [w for w in (b"demo@example.com",) if w in raw]
        line(not leaked, "no known plaintext found in the database file")

    print("\n" + ("All checks passed." if ok else "Fix the FAIL lines above."))
    return 0 if ok else 1


def encrypt_profiles():
    """Rewrite plaintext `user.profile_data` rows as ciphertext.

    `profile_data` shipped unencrypted and was encrypted afterwards, so any
    database created in between holds plaintext JSON in that column. The column
    type tolerates those rows on read so the app still works, but tolerating is
    not fixing: they are still readable to anyone holding the database file.

    This walks every row, leaves the ones already encrypted alone, and rewrites
    the rest. Safe to run more than once, and safe to run on a database that
    never had the problem.
    """
    from sqlalchemy import text

    from veritagnosis import db
    from veritagnosis.crypto import encrypt, looks_encrypted

    db.init_db()
    converted = already = skipped = 0

    with db.engine.begin() as conn:
        rows = conn.execute(
            text("SELECT id, profile_data FROM user WHERE profile_data IS NOT NULL")
        ).fetchall()

        for row_id, value in rows:
            if not value:
                continue
            if looks_encrypted(value):
                already += 1
                continue
            try:
                blob = encrypt(value, "user.profile")
            except Exception as exc:                      # noqa: BLE001
                # Never drop a student's data because one row is odd; report it
                # and move on so the rest of the migration still lands.
                print(f"  ! row {row_id} could not be encrypted: {exc}")
                skipped += 1
                continue
            conn.execute(
                text("UPDATE user SET profile_data = :v WHERE id = :i"),
                {"v": blob, "i": row_id},
            )
            converted += 1

    print(f"Encrypted {converted} profile row(s).")
    print(f"{already} were already encrypted.")
    if skipped:
        print(f"{skipped} could not be converted and were left as they were.")
    return 0


