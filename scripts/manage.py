#!/usr/bin/env python3
"""
Project admin tasks.

    python scripts/manage.py init-keys     generate .env with fresh secrets
    python scripts/manage.py init-db       create tables
    python scripts/manage.py import-colleges <csv>   load the College Scorecard
    python scripts/manage.py seed-colleges  freeze the catalogue for the exe
    python scripts/manage.py seed-quotes   load the quote pools
    python scripts/manage.py demo-user     create a demo account
    python scripts/manage.py check         report on the security configuration
    python scripts/manage.py encrypt-profiles  encrypt profile rows written
                                           before that column was encrypted
    python scripts/manage.py email-setup   connect Gmail so codes get emailed
    python scripts/manage.py email-test    send yourself a test code
"""

from __future__ import annotations

import secrets
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE))

ENV = BASE / ".env"

# ASCII only, deliberately. This file is parsed by python-dotenv, which
# always reads UTF-8; on Windows, writing it with the default locale
# encoding turns a character like an em dash into a byte dotenv cannot
# decode, and the app dies on startup with a UnicodeDecodeError.
TEMPLATE = """# Generated by scripts/manage.py init-keys - NEVER COMMIT THIS FILE.
# Losing these keys means every encrypted column becomes unreadable. There is
# no recovery: that is the point. Back them up somewhere that is not the repo.

VG_FIELD_KEY={field}
VG_INDEX_KEY={index}

# Optional whole-file encryption (needs: pip install sqlcipher3-binary)
# VG_ENCRYPT_DB=1
# VG_DB_KEY={db}

# --- Gmail, for sending the verification code ---
# Leave blank and the code prints in your terminal instead.
# VG_SMTP_USER is the full Gmail address; VG_SMTP_PASSWORD is a 16-character
# App password from Google Account > Security > App passwords (needs 2-Step
# Verification turned on). Never your normal Google password.
VG_SMTP_USER=
VG_SMTP_PASSWORD=
VG_MAIL_FROM_NAME=Veritagnosis

VG_SESSION_TTL_HOURS=168
VG_SESSION_IDLE_HOURS=24
VG_MAX_FAILED_LOGINS=8
VG_LOCKOUT_MINUTES=15
VG_DEBUG=0
"""


def init_keys():
    if ENV.exists():
        print(f"{ENV} already exists. Delete it first if you really mean to "
              f"rotate keys — every encrypted value will become unreadable.")
        return 1
    body = TEMPLATE.format(
        field=secrets.token_urlsafe(32),
        index=secrets.token_urlsafe(32),
        db=secrets.token_urlsafe(32),
    )
    assert body.isascii(), "the .env template must stay ASCII"
    # encoding and newline pinned: Windows would otherwise use the local
    # code page, which python-dotenv cannot read back.
    ENV.write_text(body, encoding="utf-8", newline="\n")
    print(f"Wrote {ENV}")
    print("Confirm .env is in .gitignore before your next commit.")
    return 0


def init_db():
    from veritagnosis import db
    db.init_db()
    print(f"Tables created in {db.config.DB_PATH}")
    return 0


